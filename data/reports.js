function num(s) {
  if (s == null) return null;
  const t = String(s).trim();
  if (t === '' || t === '—') return null;
  const n = parseFloat(t.replace(/,/g, ''));
  return Number.isNaN(n) ? null : n;
}
function shortLabel(period) {            // "May 2026" → "May 26"
  return period.slice(0, 3) + ' ' + period.slice(-2);
}
function pad12(arr) {
  const a = arr.map(num);
  while (a.length < 12) a.push(null);
  return a;
}

